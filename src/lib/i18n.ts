export type TranslationKey = keyof typeof translations['it-IT'];

export const getTranslation = (key: TranslationKey, replacements?: Record<string, string | number>): string => {
  const rawLang = getRegionLanguage();
  // Normalize language key to match our dictionary
  const lang = (rawLang === 'en-US' || rawLang === 'es-ES') ? rawLang : 'it-IT';
  const dict = translations[lang] || translations['it-IT'];
  let text = dict[key] || translations['it-IT'][key] || String(key);
  
  if (replacements) {
    Object.entries(replacements).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
};

